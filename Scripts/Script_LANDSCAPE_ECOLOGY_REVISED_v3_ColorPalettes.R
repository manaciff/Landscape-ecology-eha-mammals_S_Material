message("\n[Export] Supplementary table of competitive models...")

build_competitive_table <- function(results_list, group_name) {
  out <- list()
  for (taxon in names(results_list)) {
    dredge_table <- results_list[[taxon]]$table
    if (is.null(dredge_table)) next
    
    competitive <- as.data.frame(subset(dredge_table, delta < 2))
    if (nrow(competitive) == 0) next
    
    metric_cols <- c("df", "logLik", "AICc", "delta", "weight")
    var_cols    <- setdiff(names(competitive), metric_cols)
    
    formulas <- vapply(seq_len(nrow(competitive)), function(i) {
      vars_present <- var_cols[!is.na(competitive[i, var_cols])]
      vars_present <- vars_present[vars_present != "(Intercept)"]
      if (length(vars_present) == 0) "~ Null Model ~" else paste(vars_present, collapse = " + ")
    }, character(1))
    
    out[[taxon]] <- data.frame(
      Group              = group_name,
      Taxon              = taxon,
      Rank               = seq_len(nrow(competitive)),
      Selected_Variables = formulas,
      df                 = competitive$df,
      LogLik             = round(competitive$logLik, 3),
      AICc               = round(competitive$AICc, 3),
      Delta_AICc         = round(competitive$delta, 3),
      Akaike_Weight      = round(competitive$weight, 3)
    )
  }
  bind_rows(out)
}

