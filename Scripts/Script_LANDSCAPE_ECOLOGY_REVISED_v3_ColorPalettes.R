# 6. RESIDUAL DIAGNOSTICS (DHARMa)
# ==============================================================================
message("\n[Diagnostics] DHARMa residual diagnostics...")

dharma_diagnostics <- function(model_list, targets, category_name,
                               n_sim = 1000, seed = GLOBAL_SEED) {
  out <- list()
  for (target_name in targets) {
    model_obj <- model_list[[target_name]]
    if (is.null(model_obj)) next
    
    model <- model_obj$model
    if (inherits(model, "averaging")) {
      model <- get.models(model_obj$table, subset = 1)[[1]]
    }
    
    set.seed(seed)
    sim <- simulateResiduals(fittedModel = model, n = n_sim, seed = seed)
    dispersion_test <- testDispersion(sim, plot = FALSE)
    uniformity_test <- testUniformity(sim, plot = FALSE)
    outlier_test    <- testOutliers(sim, plot = FALSE)
    
    out[[target_name]] <- data.frame(
      Category = category_name,
      Taxon = target_name,
      n_obs = model_obj$n,
      Dispersion_p = round(dispersion_test$p.value, 4),
      Uniformity_p = round(uniformity_test$p.value, 4),
      Outliers_p   = round(outlier_test$p.value, 4),
      Overall_Diagnostic = ifelse(
        dispersion_test$p.value > 0.05 & uniformity_test$p.value > 0.05 & outlier_test$p.value > 0.05,
        "OK", "WARNING"
      )
    )
  }
  bind_rows(out)
}

