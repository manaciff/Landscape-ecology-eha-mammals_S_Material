# Global PERMANOVA (adonis2) for all grouping variables
# Run before pairwise tests: pairwise decomposition is only interpretable when
# the global test is significant (Anderson & Walsh 2013, Ecology).
# ------------------------------------------------------------------------------
tidy_adonis <- function(adonis_obj, group_label) {
  row <- as.data.frame(adonis_obj)[1L, ]
  data.frame(
    Grouping = group_label,
    Df       = row$Df,
    SumOfSqs = round(row$SumOfSqs, 4),
    R2       = round(row$R2, 4),
    F_value  = round(row$F, 4),
    p_value  = row[["Pr(>F)"]]
  )
}

