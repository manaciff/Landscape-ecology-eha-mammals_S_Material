# B) Pairwise PERMANOVA with FDR correction
# Permutations standardized to N_PERM (9,999); set.seed asserted at each call.
pairwise.adonis <- function(x, factors, sim.method = 'euclidean',
                            p.adjust.m = 'fdr', n_perm = N_PERM, seed = GLOBAL_SEED) {
  co <- combn(unique(as.character(factors)), 2)
  pairs <- character(0); F.Model <- numeric(0); R2 <- numeric(0); p.value <- numeric(0)
  
  for (elem in seq_len(ncol(co))) {
    sub_idx <- factors %in% c(co[1, elem], co[2, elem])
    x1 <- vegdist(x[sub_idx, ], method = sim.method)
    
    set.seed(seed)  # reproducibility within the loop
    ad <- adonis2(x1 ~ factors[sub_idx], permutations = n_perm)
    
    pairs   <- c(pairs, paste(co[1, elem], 'vs', co[2, elem]))
    F.Model <- c(F.Model, ad$F[1])
    R2      <- c(R2, ad$R2[1])
    p.value <- c(p.value, ad$`Pr(>F)`[1])
  }
  
  p.adjusted <- p.adjust(p.value, method = p.adjust.m)
  
  data.frame(
    pairs = pairs,
    F.Model = round(F.Model, 4),
    R2 = round(R2, 4),
    p.value = round(p.value, 4),
    p.adjusted = round(p.adjusted, 4),
    sig = ifelse(p.adjusted < 0.05, '*', '')
  )
}

# C) GLMM + GLM model selection
# Max terms logic: 2 when n < 15; otherwise floor(n/10) capped at 5.
# Exclusion rules prevent structural collinearity in the same formula.
run_model_selection <- function(target_name, filter_col, full_data) {
  
  data_subset <- full_data %>% filter(.data[[filter_col]] == target_name)
  
  # Constant addition for Gamma compatibility (see header note)
  data_subset$EHA_ha <- ifelse(data_subset$EHA_ha == 0, 0.001, data_subset$EHA_ha)
  
  n <- nrow(data_subset)
  if (n < 5) return(NULL)
  
  n_spp <- length(unique(data_subset$SPECIES))
  # Restore na.action on function exit to avoid persistent global side effects
  old_na_action <- getOption("na.action")
  on.exit(options(na.action = old_na_action), add = TRUE)
  options(na.action = "na.fail")
  
  # Exclusion rule preventing structurally collinear metrics in the same formula
  subset_rule <- expression(!(PD_Forest && PLAND_Forest) &
                              !(PROX_MN_Forest && PD_Forest) &
                              !(PROX_MN_Forest && PLAND_Forest) &
                              !(Mean_AREA_Forest_ha && Mean_ENN_Forest_m) &
                              !(ED_Forest && PD_Forest))
  
  # Dynamic complexity ceiling
  max_terms <- if (n < 15) 2 else min(5, max(2, floor(n / 10)))
  
  global_model <- NULL
  
  # GLMM for functionally grouped subsets (>1 species)
  if (n_spp > 1) {
    global_model <- tryCatch({
      glmer(EHA_ha ~ PLAND_Forest + NP_Forest + PD_Forest +
              Mean_FRAC_Forest + PROX_MN_Forest + Mean_AREA_Forest_ha + ED_Forest +
              Mean_Elevation_m + Mean_Pop_Density + Mean_ENN_Forest_m +
              (1 | SPECIES),
            data = data_subset, family = Gamma(link = "log"),
            control = glmerControl(optimizer = "bobyqa",
                                   optCtrl = list(maxfun = 100000)))
    }, error = function(e) {
      message(sprintf("   GLMM convergence failure for %s. Reverting to fixed-effects GLM.", target_name))
      NULL
    })
  }
  
  # Fixed-effects GLM as fallback or for single-species subsets
  if (is.null(global_model)) {
    global_model <- glm(EHA_ha ~ PLAND_Forest + NP_Forest + PD_Forest +
                          Mean_FRAC_Forest + PROX_MN_Forest + Mean_AREA_Forest_ha + ED_Forest +
                          Mean_Elevation_m + Mean_Pop_Density + Mean_ENN_Forest_m,
                        data = data_subset, family = Gamma(link = "log"))
  }
  
  dredge_table <- dredge(global_model, rank = "AICc",
                         m.lim = c(0, max_terms), trace = FALSE,
                         subset = subset_rule)
  
  # Model averaging across competitive models (delta AICc < 2)
  competitive_models <- get.models(dredge_table, subset = delta < 2)
  
  if (length(competitive_models) == 1) {
    final_model <- competitive_models[[1]]
    summary_msg <- "Single most parsimonious model retained."
  } else {
    final_model <- model.avg(competitive_models, fit = TRUE)
    summary_msg <- sprintf("%d competitive models retained for Model Averaging.",
                           length(competitive_models))
  }
  message(sprintf("   [%s] %s", target_name, summary_msg))
  
  list(table = dredge_table, model = final_model, n = n,
       n_competitive = length(competitive_models))
}

# D) Response curves visualization (with centralized color reference)
plot_response_curves <- function(model_obj, target_name, original_df,
                                 use_log_y = TRUE, line_color = "black",
                                 show_y_label = TRUE) {
  if (is.null(model_obj)) return(NULL)
  model <- model_obj$model
  
  if (inherits(model, "averaging")) {
    model <- get.models(model_obj$table, subset = 1)[[1]]
  }
  
  mod_data <- model.frame(model)
  
  if (inherits(model, "merMod")) {
    terms_raw <- attr(terms(formula(model, fixed.only = TRUE)), "term.labels")
  } else {
    terms_raw <- attr(terms(model), "term.labels")
  }
  
  simple_terms <- terms_raw[!grepl(":", terms_raw)]
  if (length(simple_terms) == 0) return(NULL)
  
  pred_list <- list()
  for (var in simple_terms) {
    min_z <- min(mod_data[[var]], na.rm = TRUE)
    max_z <- max(mod_data[[var]], na.rm = TRUE)
    seq_z <- seq(min_z, max_z, length.out = 100)
    
    emm <- as.data.frame(emmeans(model,
                                 specs = as.formula(paste("~", var)),
                                 at = setNames(list(seq_z), var),
                                 type = "response"))
    
    pred_col <- names(emm)[2]
    col_min  <- names(emm)[ncol(emm) - 1]
    col_max  <- names(emm)[ncol(emm)]
    
    media_orig <- mean(original_df[[var]], na.rm = TRUE)
    sd_orig    <- sd(original_df[[var]], na.rm = TRUE)
    
    pred_list[[var]] <- data.frame(
      Variable = var,
      x_real   = (emm[[var]] * sd_orig) + media_orig,
      y_pred   = emm[[pred_col]],
      y_min    = emm[[col_min]],
      y_max    = emm[[col_max]]
    )
  }
  
  df_preds <- bind_rows(pred_list)
  df_points <- original_df %>%
    filter(GENUS == target_name | LOCOMOTION == target_name | DIET == target_name) %>%
    select(any_of(c("EHA_ha", simple_terms))) %>%
    pivot_longer(cols = any_of(simple_terms), names_to = "Variable", values_to = "Valor_X") %>%
    mutate(EHA_ha = ifelse(EHA_ha == 0, 0.001, EHA_ha))
  
  nice_names <- c("PLAND_Forest"        = "Forest\nCover (%)",
                  "NP_Forest"           = "Number of\nPatches",
                  "PD_Forest"           = "Patch\nDensity",
                  "Mean_FRAC_Forest"    = "Fractal\nDimension",
                  "PROX_MN_Forest"      = "Proximity\nIndex",
                  "Mean_AREA_Forest_ha" = "Patch Area\n(ha)",
                  "ED_Forest"           = "Edge\nDensity",
                  "Mean_ENN_Forest_m"   = "Euclidean NN\nDistance (m)",
                  "Mean_Elevation_m"    = "Elevation\n(m)",
                  "Mean_Pop_Density"    = "Human\nPopulation")
  
  df_preds$Variable  <- dplyr::recode(df_preds$Variable, !!!nice_names)
  df_points$Variable <- dplyr::recode(df_points$Variable, !!!nice_names)
  
  p <- ggplot() +
    geom_point(data = df_points, aes(x = Valor_X, y = EHA_ha),
               alpha = 0.4, size = 2, color = "grey40") +
    geom_ribbon(data = df_preds, aes(x = x_real, ymin = y_min, ymax = y_max),
                fill = line_color, alpha = 0.2) +
    geom_line(data = df_preds, aes(x = x_real, y = y_pred),
              color = line_color, linewidth = 1) +
    facet_wrap(~Variable, scales = "free_x", strip.position = "top") +
    labs(x = NULL, y = "Effective Habitat Area (ha)",
         title = bquote(italic(.(target_name)) ~ "EHA Response Models")) +
    theme_classic(base_size = 10, base_family = "sans") +
    theme(strip.background = element_blank(),
          strip.text       = element_text(face = "bold", size = 9),
          plot.title       = element_text(face = "bold", size = 11, hjust = 0.5),
          axis.text.x      = element_text(size = 8.5),
          axis.title.y     = element_text(color = ifelse(show_y_label, "black", "transparent")))
  
  if (use_log_y) {
    p <- p + scale_y_log10(labels = label_comma())
  } else {
    p <- p + scale_y_continuous(labels = label_comma())
  }
  p + scale_x_continuous(labels = label_comma(), n.breaks = 4,
                         guide = guide_axis(n.dodge = 2))
}

# E) Extraction of variable importance (Akaike weights) and coefficient direction
# Direction is derived from the sign of model-averaged (or best-model) coefficients,
# not from Importance values, which are always non-negative.
extract_variable_importance <- function(results_list, group_name) {
  imp_list <- list()
  for (taxon in names(results_list)) {
    result     <- results_list[[taxon]]
    dredge_obj <- result$table
    model_obj  <- result$model
    if (!is.null(dredge_obj)) {
      imp   <- sw(dredge_obj)
      terms <- names(imp)

      coefs   <- tryCatch(coef(model_obj),
                          error = function(e) setNames(rep(NA_real_, length(terms)), terms))
      matched <- coefs[match(terms, names(coefs))]
      direction <- dplyr::case_when(
        !is.na(matched) & matched > 0 ~ "+",
        !is.na(matched) & matched < 0 ~ "-",
        TRUE                          ~ ""
      )

      imp_list[[taxon]] <- data.frame(
        Group      = group_name,
        Taxon      = taxon,
        Variable   = terms,
        Importance = as.numeric(imp),
        Direction  = direction,
        stringsAsFactors = FALSE
      )
    }
  }
  bind_rows(imp_list)
}

